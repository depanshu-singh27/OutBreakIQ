export const COUNTRY_PM25_FOR_MAP: Record<string, number> = { ...CORE, ...EXTRA };
export function getPM25ForMap(alpha3: string, latitude: number): number {
    const a = alpha3.toUpperCase();
    if (COUNTRY_PM25_FOR_MAP[a] != null)
        return COUNTRY_PM25_FOR_MAP[a]!;
    const absLat = Math.abs(latitude);
    if (absLat < 15)
        return 28;
    if (absLat < 30)
        return 45;
    if (absLat < 45)
        return 18;
    return 9;
}
export function pm25StepColor(val: number): string {
    if (val >= 150)
        return '#7b0000';
    if (val >= 100)
        return '#d73027';
    if (val >= 55)
        return '#f97316';
    if (val >= 35)
        return '#fbbf24';
    if (val >= 15)
        return '#86efac';
    return '#10b981';
}
